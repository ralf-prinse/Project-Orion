from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from enum import Enum


class TradeStatus(str, Enum):
    """
    Current lifecycle state of a trade.
    """

    PENDING = "PENDING"
    OPEN = "OPEN"
    CLOSED = "CLOSED"


class ExitSignal(str, Enum):
    """
    Deterministic exit decision generated by Orion.

    The Position Monitor is the only component that
    may produce these signals.
    """

    HOLD_POSITION = "HOLD_POSITION"
    TAKE_PROFIT = "TAKE_PROFIT"
    STOP_LOSS = "STOP_LOSS"
    TRAILING_STOP = "TRAILING_STOP"
    EXIT_DUE_TO_WEAKNESS = "EXIT_DUE_TO_WEAKNESS"
    EXIT_DUE_TO_TIME_LIMIT = "EXIT_DUE_TO_TIME_LIMIT"


@dataclass(frozen=True)
class Trade:
    """
    Central trade domain model.

    Every trade inside Orion should eventually be
    represented by this object.

    The Trade itself contains no business logic.
    """

    # ---------- Identity ----------

    symbol: str

    # ---------- Entry ----------

    quantity: int

    entry_price: float

    entry_datetime: datetime

    entry_reason: str

    confidence: float

    # ---------- Current market ----------

    current_price: float

    highest_price: float

    lowest_price: float

    # ---------- Risk management ----------

    stop_loss: float

    take_profit: float

    trailing_stop: float | None = None

    # ---------- Status ----------

    status: TradeStatus = TradeStatus.OPEN

    exit_signal: ExitSignal = ExitSignal.HOLD_POSITION

    exit_reason: str = ""

    # ---------- Exit ----------

    exit_price: float | None = None

    exit_datetime: datetime | None = None

    # ---------- Performance ----------

    realized_profit_loss: float = 0.0

    unrealized_profit_loss: float = 0.0

    unrealized_profit_loss_percent: float = 0.0

    # ---------- Metadata ----------

    notes: str = ""